// The flag has different pole and banner proportions in the marker and pin.
function flagPath(pin: boolean) {
  const [x, y, r, bottom, bannerTop, bannerLeft, bannerMiddle, middleY, right] = pin
    ? [9.3335, 8.66663, 2 / 3, 19.3333, 9.99996, 14.7868, 14.4002, 15.3333, 18.6668]
    : [7, 6, 1, 17, 8, 12.18, 11.6, 12, 16];
  const anchor = bannerLeft + 1.22 * r;
  const d = `M${anchor} ${bannerTop}L${bannerLeft + .98*r} ${y + .8*r}
    C${bannerLeft + .89*r} ${y + .34*r} ${bannerLeft + .48*r} ${y} ${bannerLeft} ${y}
    H${x+r}C${x+.45*r} ${y} ${x} ${y+.45*r} ${x} ${y+r}
    V${bottom}C${x} ${bottom+.55*r} ${x+.45*r} ${bottom+r} ${x+r} ${bottom+r}
    C${x+1.55*r} ${bottom+r} ${x+2*r} ${bottom+.55*r} ${x+2*r} ${bottom}
    V${middleY}H${bannerMiddle}L${bannerMiddle+.24*r} ${middleY+1.2*r}
    C${bannerMiddle+.33*r} ${middleY+1.67*r} ${bannerMiddle+.74*r} ${middleY+2*r} ${bannerMiddle+1.22*r} ${middleY+2*r}
    H${right}C${right+.55*r} ${middleY+2*r} ${right+r} ${middleY+1.55*r} ${right+r} ${middleY+r}
    V${bannerTop+r}C${right+r} ${bannerTop+.45*r} ${right+.55*r} ${bannerTop} ${right} ${bannerTop}
    H${anchor}Z`;
  return { d };
}

/** Map symbols with a shared marker/pin envelope and optional active ring. */
export function MarkupIcon({
  name, small = false, edit = false, addContour = true,
  color = name === "marker" ? "currentColor" : "black", size, title, ...svgProps
}: MarkupIconProps) {
  const panorama = name === "panorama-360";
  const pin = !panorama && !small;
  const width = panorama ? 32 : pin ? 28 : 24;
  const height = panorama ? 32 : pin ? (name === "video" ? 38 : 42) + (edit ? 6 : 0) : 24;
  const renderedWidth = size ?? width;
  const symbolPaths = panorama ? panoramaPaths : name === "flag" ? [flagPath(pin)] : glyphs[name];
  const before = panorama ? [] : small
    ? [markerBackground, name === "video" ? videoMarkerContour : markerContour]
    : name === "video" ? videoPinFrame : pinFrame;
  const after = pin && name === "video" ? videoPinBase : [];
  const transform = !pin ? undefined
    : name === "cross" ? "translate(14 14) scale(0.8766666667) translate(-12 -12)"
    : name === "danger" ? "translate(1 0.5) scale(1.0833333333)"
    : name === "video" ? "translate(-4 -6) scale(1.5)"
    : name === "flag" ? undefined : "translate(2 2)";
  const contourOpacity = addContour ? 0.6 : 0;
  const renderPaths = (items: PathSpec[]) => items.map(({ fill, fillOpacity, strokeOpacity, ...path }, index) => (
    <path key={index} {...path} fill={fill === "color" ? color : fill}
      fillOpacity={fillOpacity === "contour" ? contourOpacity : fillOpacity}
      strokeOpacity={strokeOpacity === "contour" ? contourOpacity : strokeOpacity} />
  ));

  return (
    <svg {...svgProps}
      aria-hidden={title || svgProps["aria-label"] ? undefined : true}
      role={title || svgProps["aria-label"] ? "img" : undefined}
      data-icon-id={`MarkupIcon-${name}`}
      width={renderedWidth} height={renderedWidth * height / width}
      viewBox={`0 0 ${width} ${height}`} fill="none" xmlns="http://www.w3.org/2000/svg">
      {title && <title>{title}</title>}
      {renderPaths(before)}
      <g fill={panorama ? undefined : "white"} transform={transform}>{renderPaths(symbolPaths)}</g>
      {renderPaths(after)}
      {pin && edit && <>
        <circle cx={14} cy={height - 7} r={7} fill="black" fillOpacity={0.6} />
        <circle cx={14} cy={height - 7} r={6} fill="white" />
        <circle cx={14} cy={height - 7} r={4} fill={color} stroke="white" strokeWidth={4} />
      </>}
    </svg>
  );
}
