/** Road signs drawn as SVG paths with fixed, recognisable sign colours. */
export const RoadIcon = ({ name, size = 20, title, ...props }: RoadIconProps) => {
  const IconContent = icons[name];
  return (
    <svg
      aria-hidden={title ? undefined : true}
      height={size}
      role={title ? "img" : undefined}
      viewBox="0 0 24 24"
      width={size}
      fill="none"
      {...props}
    >
      {title && <title>{title}</title>}
      <IconContent />
    </svg>
  );
};
